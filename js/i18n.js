/* ════════════ I18N ENGINE ════════════ */
(function() {
  let lang = localStorage.getItem('techvin_lang') || 'en';

  function translate(key) {
    return (TECHVIN_I18N[lang] && TECHVIN_I18N[lang][key]) || (TECHVIN_I18N.en && TECHVIN_I18N.en[key]) || '';
  }

  function applyLang(newLang) {
    lang = newLang;
    localStorage.setItem('techvin_lang', newLang);
    document.documentElement.setAttribute('lang', newLang);

    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const val = translate(key);
      if (!val) return;
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.setAttribute('placeholder', val);
      } else if (el.tagName === 'OPTION') {
        el.textContent = val;
      } else {
        el.innerHTML = val;
      }
    });

    document.querySelectorAll('[data-lang-btn]').forEach(btn => {
      btn.classList.toggle('is-active', btn.getAttribute('data-lang-btn') === newLang);
    });
  }

  window.techvinTranslate = translate;
  window.techvinApplyLang = applyLang;
  window.techvinCurrentLang = () => lang;

  document.addEventListener('DOMContentLoaded', () => {
    document.querySelectorAll('[data-lang-btn]').forEach(btn => {
      btn.addEventListener('click', () => applyLang(btn.getAttribute('data-lang-btn')));
    });
    applyLang(lang);
  });
})();
